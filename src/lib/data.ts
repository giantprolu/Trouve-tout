export interface Categorie {
  slug: string;
  nom: string;
  emoji: string;
  description: string;
  sousTitre: string;
}

export interface Marque {
  slug: string;
  nom: string;
  /** Une marque d'outillage couvre plusieurs familles d'outils. */
  categorieSlugs: string[];
  description: string;
  positionnement: string;
}

export interface Produit {
  slug: string;
  nom: string;
  marqueSlug: string;
  categorieSlug: string;
  /** Prix constate chez le marchand au moment de la redaction. Affiche en fourchette de 50 € max (fourchettePrix) : peut devenir obsolete, voir CLAUDE.md section "Prix". */
  prixIndicatif: number;
  segment: 'meilleur_rapport' | 'milieu' | 'moins_cher';
  qualite: number;
  durabilite: number;
  fiabilite: number;
  verdict: string;
  pourQui: string;
  contreQui: string;
  description: string;
  marchand: Marchand;
  /** URL de la fiche produit chez le marchand. Le lien tracke est genere a l'affichage. */
  urlMarchand: string;
  /** Photo produit hebergee par le CDN ManoMano/productserve (600x600, fond blanc). Absente pour les fiches encore generiques. */
  image?: string;
  /** false = URL encore generique et fiche non relue. */
  verifie: boolean;
}

export interface Guide {
  slug: string;
  titre: string;
  description: string;
  categorieSlug: string;
  intro: string;
  sections: { titre: string; contenu: string }[];
}

